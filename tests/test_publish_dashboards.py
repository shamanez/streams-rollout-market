"""Tests for the public-snapshot dashboard publisher.

Covers the STEER.md ``dashboard.endpoint_retired`` contract: the
endpoint-coverage dashboard must NOT appear in the public surface
generated by ``scripts/live/publish_dashboards.py``.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "publish_dashboards", REPO_ROOT / "scripts" / "live" / "publish_dashboards.py"
)
publish_dashboards = importlib.util.module_from_spec(SPEC)
sys.modules["publish_dashboards"] = publish_dashboards
SPEC.loader.exec_module(publish_dashboards)  # type: ignore[union-attr]


def test_cards_does_not_contain_endpoint_slug():
    slugs = {c.get("slug") for c in publish_dashboards.CARDS}
    assert "endpoint" not in slugs
    assert "dense" in slugs
    assert "router" in slugs
    assert "agent" in slugs
    # Marketplace simulation retired — the public surface is now
    # strictly about training-inference mismatch (logprob + routing).
    assert "marketplace" not in slugs


def test_headlines_does_not_contain_endpoint_key():
    assert "endpoint" not in publish_dashboards._HEADLINES


def _split_headline_and_footer(page: str) -> tuple[str, str]:
    """The "headline section" is everything before the <footer> tag.

    STEER.md "Engines shown on the headline" — retired dashboards may
    still leak into a non-headline area (e.g. an appendix), but the
    headline must be clean. We treat the page up to <footer> as the
    headline section for this test.
    """
    marker = "<footer"
    idx = page.find(marker)
    if idx == -1:
        return page, ""
    return page[:idx], page[idx:]


def test_rendered_index_headline_has_no_endpoint_dashboard_string():
    # All cards missing — exercises the same render path as a real
    # publish, just without copying real HTML/JSON into out_dir.
    card_data = [{**c, "ready": False} for c in publish_dashboards.CARDS]
    page = publish_dashboards.render_index(card_data)
    headline, _ = _split_headline_and_footer(page)
    assert "endpoint_dashboard" not in headline
    assert "Endpoint identity-gap dashboard" not in headline
    # Sanity: the three target dashboards still render.
    assert "Dense mismatch dashboard" in headline
    assert "MoE router dashboard" in headline
    assert "Agent trajectory viewer" in headline


def test_rendered_index_hermes_router_matrix_empty_payload_renders_tbd():
    """With no real router_dashboard payload, the router matrix still
    renders — both trainer rows fall through to the TBD tile renderer.
    The legacy yellow ``router-flip-rate-placeholder`` section is gone."""
    card_data = [{**c, "ready": False, "payload": {}} for c in publish_dashboards.CARDS]
    page = publish_dashboards.render_index(card_data)
    # New live router matrix is present.
    assert 'data-section="hermes-agent-moe-router-matrix"' in page
    matrix_start = page.find('data-section="hermes-agent-moe-router-matrix"')
    matrix_end = page.find("</section>", matrix_start)
    matrix_html = page[matrix_start:matrix_end]
    assert "Hermes Agent — MoE router (Qwen3-30B-A3B)" in matrix_html
    # Empty payload → both rows are TBD tiles.
    assert "FSDP" in matrix_html and "MEGATRON" in matrix_html
    assert matrix_html.count("mx-tbd") >= 2
    # Old yellow placeholder is gone.
    assert 'data-section="router-flip-rate-placeholder"' not in page
    # The legacy cycle-2 matrices stay retired.
    assert 'data-section="dense-matrix"' not in page
    assert 'data-section="moe-matrix"' not in page
    # The Hermes Agent matrices remain the headline.
    assert "Hermes Agent — Dense (Qwen3-32B)" in page
    assert "Hermes Agent — MoE (Qwen3-30B-A3B)" in page


def test_rendered_index_hermes_router_matrix_with_real_payload():
    """With a populated router payload, the matrix shows a real
    flip-rate tile for the FSDP row; Megatron stays TBD until that
    leg is provisioned. Color band follows the plan thresholds: 3.5%
    → green."""
    fsdp_payload = {
        "engine_pairs": [
            {
                "rollout_engine": "hermes-qwen3-30b-a3b-bf16",
                "trainer_engine": "fsdp-bf16-moe",
                "count": 1,
                "mean_router_flip_rate": 0.035,
                "mean_token_expert_disagreement_rate": 1.0,
                "worst_layer_flip_rate": 0.136,
                "total_tokens": 22,
                "layer_count": 48,
            }
        ],
        "rows": [],
        "num_runs": 1,
    }
    card_data = []
    for c in publish_dashboards.CARDS:
        if c["slug"] == "router":
            card_data.append({**c, "ready": False, "payload": fsdp_payload})
        else:
            card_data.append({**c, "ready": False, "payload": {}})
    page = publish_dashboards.render_index(card_data)
    matrix_start = page.find('data-section="hermes-agent-moe-router-matrix"')
    matrix_end = page.find("</section>", matrix_start)
    matrix_html = page[matrix_start:matrix_end]
    # FSDP tile carries the green class + percentage value.
    assert "mx-good" in matrix_html
    assert "3.50%" in matrix_html
    # Megatron tile stays TBD.
    assert "mx-tbd" in matrix_html


def test_rendered_index_with_ready_cards_has_no_endpoint_link():
    card_data = []
    for c in publish_dashboards.CARDS:
        card_data.append({
            **c,
            "ready": True,
            "filename": f"{c['slug']}_dashboard.html",
            "summary": "",
            "payload": {},
        })
    page = publish_dashboards.render_index(card_data)
    headline, _ = _split_headline_and_footer(page)
    assert "endpoint_dashboard.html" not in headline
    assert "endpoint_dashboard" not in headline
